#ifndef LOGGER_RTC_SERVICE_H
#define LOGGER_RTC_SERVICE_H


/*
 * ============================================================================
 * rtc_service.h
 * ============================================================================
 *
 * Модуль обслуживания аппаратных часов реального времени (RTC)
 * микроконтроллера STM32L4P5RET6.
 *
 * НАЗНАЧЕНИЕ:
 *
 * 1. Установка даты и времени аппаратного RTC.
 *
 * 2. Чтение текущей даты и времени аппаратного RTC.
 *
 * 3. Предоставление единого интерфейса для работы с RTC
 *    другим модулям программы LOGGER.
 *
 * ============================================================================
 *
 * АРХИТЕКТУРА:
 *
 * gps.c:
 *     Принимает и обрабатывает NMEA-предложения GPS.
 *     Непосредственно с аппаратным RTC не работает.
 *
 * rtc_service.c:
 *     Выполняет операции чтения и установки аппаратного RTC
 *     через функции STM32 HAL.
 *
 * logger_state_machine.c:
 *     Использует RTC для синхронизации времени и проверки
 *     GPS-спуфинга.
 *
 * ============================================================================
 *
 * ВАЖНО:
 *
 * - Все даты и время RTC используются в формате UTC.
 *
 * - Аппаратный RTC STM32 хранит год в диапазоне 00...99.
 *
 * - В структуре GPS_TimeStamp год представлен полностью:
 *   например, 2026.
 *
 * - Для LOGGER используется диапазон годов 2000...2099.
 *
 * - Первоначальная синхронизация RTC выполняется по GPS
 *   в режиме MODE_TEST.
 *
 * - После первоначальной синхронизации RTC работает независимо.
 *
 * - При каждом последующем получении GPS-координат повторная
 *   синхронизация RTC НЕ выполняется.
 *
 * ============================================================================
 */


#include "main.h"
#include "logger_types.h"


/*
 * ============================================================================
 * RTC_Service_SetTime()
 * ============================================================================
 *
 * НАЗНАЧЕНИЕ:
 *
 * Устанавливает дату и время аппаратного RTC STM32.
 *
 * ПАРАМЕТР:
 *
 * timestamp:
 *     Указатель на структуру GPS_TimeStamp, содержащую
 *     дату и время UTC.
 *
 *     year   - полный год (2000...2099);
 *     month  - месяц (1...12);
 *     day    - день месяца;
 *     hour   - часы (0...23);
 *     minute - минуты (0...59);
 *     second - секунды (0...59).
 *
 * РАБОТА:
 *
 * - Проверяет входные данные.
 *
 * - Преобразует полный год в формат аппаратного RTC.
 *
 * - Вычисляет день недели.
 *
 * - Устанавливает время и дату через STM32 HAL.
 *
 * ВОЗВРАЩАЕТ:
 *
 * HAL_OK:
 *     Дата и время успешно установлены.
 *
 * HAL_ERROR:
 *     Некорректный указатель, недопустимые данные
 *     либо ошибка установки RTC.
 *
 * ВАЖНО:
 *
 * Функция вызывается стейт-машиной только тогда,
 * когда необходима синхронизация RTC.
 *
 * Она НЕ должна автоматически вызываться
 * при каждом новом GPS-пакете.
 * ============================================================================
 */
HAL_StatusTypeDef RTC_Service_SetTime(const GPS_TimeStamp *timestamp);


/*
 * ============================================================================
 * RTC_Service_GetTime()
 * ============================================================================
 *
 * НАЗНАЧЕНИЕ:
 *
 * Считывает текущую дату и время аппаратного RTC STM32.
 *
 * ПАРАМЕТР:
 *
 * timestamp:
 *     Указатель на структуру GPS_TimeStamp,
 *     в которую записываются показания RTC.
 *
 * РАБОТА:
 *
 * - Считывает текущее время аппаратного RTC.
 *
 * - Затем считывает текущую дату аппаратного RTC.
 *
 * - Преобразует двузначный год RTC в полный год.
 *
 * - Заполняет структуру GPS_TimeStamp.
 *
 * ВАЖНО:
 *
 * Для STM32 HAL необходимо соблюдать порядок:
 *
 *     1. HAL_RTC_GetTime()
 *     2. HAL_RTC_GetDate()
 *
 * Это необходимо для корректного обновления
 * теневых регистров RTC.
 *
 * Функция НЕ изменяет аппаратные часы.
 *
 * ВОЗВРАЩАЕТ:
 *
 * HAL_OK:
 *     Дата и время успешно прочитаны.
 *
 * HAL_ERROR:
 *     Некорректный указатель либо ошибка чтения RTC.
 * ============================================================================
 */
HAL_StatusTypeDef RTC_Service_GetTime(GPS_TimeStamp *timestamp);


#endif /* LOGGER_RTC_SERVICE_H */