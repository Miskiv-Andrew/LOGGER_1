#ifndef LOGGER_GPS_H
#define LOGGER_GPS_H


#include "main.h"
#include <stdint.h>


/*
 * ============================================================================
 * GPS LOGGER
 * ============================================================================
 *
 * GPS подключён к USART3.
 *
 * GPS после включения питания непрерывно передаёт NMEA-предложения.
 * Для получения координат и времени LOGGER использует предложение:
 *
 *     $GNRMC
 *
 * Приём данных выполняется через:
 *
 *     USART3 + DMA + HAL_UARTEx_ReceiveToIdle_DMA()
 *
 * DMA работает в циклическом режиме.
 *
 * ВАЖНО:
 *
 * 1. Разбор NMEA НЕ выполняется из прерывания.
 *
 * 2. HAL_UARTEx_RxEventCallback() сообщает gps.c только о появлении
 *    очередной порции принятых данных.
 *
 * 3. После получения новых данных поднимается флаг gps_info.
 *
 * 4. Накопленные данные разбираются из основного цикла программы
 *    в состоянии GPS_PROC.
 *
 * 5. Если после очередного события приёма полного корректного $GNRMC
 *    ещё нет, уже полученные данные НЕ теряются.
 *
 *    Они сохраняются и дополняются следующими принятыми байтами.
 *
 *    Это необходимо, поскольку начало приёма может произойти в любой
 *    момент непрерывного потока NMEA и предложение $GNRMC может быть
 *    разделено между несколькими событиями приёма DMA.
 *
 * 6. Контроль времени ожидания ответа GPS НЕ выполняется внутри gps.c
 *    через HAL_GetTick().
 *
 *    Для этого используется общий аппаратный таймер контроля ответа
 *    приборов TIM3.
 *
 * 7. Проверка спуфинга и проверка нахождения координаты внутри области
 *    разведки будут реализованы позже, когда будут окончательно
 *    определены соответствующие параметры и алгоритмы.
 * ============================================================================
 */


/*
 * ============================================================================
 * Размер DMA-буфера GPS.
 * ============================================================================
 *
 * Размер выбран заранее для текущей реализации LOGGER.
 *
 * DMA циклически записывает сюда данные, поступающие от GPS через USART3.
 */
#define GPS_DMA_RX_BUFFER_SIZE       700U


/*
 * ============================================================================
 * Размер накопительного буфера GPS.
 * ============================================================================
 *
 * Этот буфер нужен не для одного конкретного DMA-события.
 *
 * В нём сохраняются данные, накопленные за несколько событий приёма,
 * пока из них не удастся выделить полный корректный $GNRMC.
 *
 * Размер пока выбран с запасом.
 *
 * Если при реальных испытаниях GPS потребуется другое значение,
 * оно будет скорректировано отдельно.
 */
#define GPS_RX_BUFFER_SIZE           2048U


/*
 * ============================================================================
 * Структура проверенных данных GPS.
 * ============================================================================
 *
 * Структура заполняется ТОЛЬКО после того, как из принятого потока
 * найден и успешно проверен корректный $GNRMC.
 *
 * latitude / longitude:
 *     координаты в десятичных градусах.
 *
 *     Северная широта  -> положительное значение.
 *     Южная широта     -> отрицательное значение.
 *     Восточная долгота -> положительное значение.
 *     Западная долгота  -> отрицательное значение.
 *
 * hour / minute / second:
 *     время UTC, полученное из $GNRMC.
 *
 * day / month / year:
 *     дата, полученная из $GNRMC.
 *
 * year содержит две последние цифры года.
 * Например:
 *
 *     2026 -> 26
 */
typedef struct
{
    float latitude;
    float longitude;

    uint8_t hour;
    uint8_t minute;
    uint8_t second;

    uint8_t day;
    uint8_t month;
    uint8_t year;

} GPS_Fix;


/*
 * ============================================================================
 * Флаг наличия новой информации GPS.
 * ============================================================================
 *
 * gps_info устанавливается при поступлении новой порции данных USART3.
 *
 * Флаг устанавливается из контекста HAL_UARTEx_RxEventCallback().
 *
 * В состоянии GPS_PROC стейт-машина проверяет этот флаг.
 *
 * Если:
 *
 *     gps_info == 1
 *
 * значит после предыдущей обработки GPS появились новые данные,
 * которые необходимо попытаться разобрать.
 *
 * После начала обработки GPS_PROC флаг должен быть сброшен.
 *
 * volatile необходим, поскольку значение изменяется из callback,
 * а читается из основного цикла программы.
 */
extern volatile uint8_t gps_info;


/*
 * ============================================================================
 * GPS_Init()
 * ============================================================================
 *
 * Выполняет программную инициализацию GPS-подсистемы.
 *
 * Функция НЕ запускает приём USART3.
 *
 * Она только приводит внутренние переменные, индексы, накопительные
 * буферы и флаги gps.c в исходное состояние.
 *
 * Вызывается один раз при запуске LOGGER из main().
 */
void GPS_Init(void);


/*
 * ============================================================================
 * GPS_StartReceive()
 * ============================================================================
 *
 * Начинает приём непрерывного NMEA-потока GPS через:
 *
 *     USART3 + ReceiveToIdle DMA.
 *
 * Перед началом нового сеанса приёма:
 *
 * - сбрасывается состояние предыдущего приёма;
 * - очищается накопленная GPS-информация;
 * - сбрасывается gps_info;
 * - устанавливается начальная позиция обработки циклического DMA;
 * - запускается HAL_UARTEx_ReceiveToIdle_DMA().
 *
 * ВАЖНО:
 *
 * Эта функция НЕ запускает TIM3.
 *
 * Таймер контроля ответа прибора относится к логике стейт-машины
 * и будет запускаться отдельно в состоянии REQ_GPS.
 *
 * Возвращает результат HAL запуска DMA-приёма.
 */
HAL_StatusTypeDef GPS_StartReceive(void);


/*
 * ============================================================================
 * GPS_StopReceive()
 * ============================================================================
 *
 * Останавливает приём GPS через USART3 DMA.
 *
 * Используется после получения корректных координат и времени,
 * а также при завершении/прерывании текущего сеанса работы с GPS.
 *
 * Функция НЕ управляет TIM3.
 *
 * Остановка таймера контроля ответа выполняется отдельно логикой
 * стейт-машины.
 */
void GPS_StopReceive(void);


/*
 * ============================================================================
 * GPS_RxEventCallback()
 * ============================================================================
 *
 * Вызывается из общего:
 *
 *     HAL_UARTEx_RxEventCallback()
 *
 * для USART3.
 *
 * Параметр size — значение Size, полученное от HAL.
 *
 * USART3 RX DMA работает в режиме DMA_CIRCULAR, поэтому функция должна
 * определить, какая именно часть DMA-буфера появилась после предыдущего
 * события, включая случай перехода DMA через конец циклического буфера.
 *
 * Новые байты переносятся во внутренний накопительный буфер GPS.
 *
 * После получения новых данных устанавливается:
 *
 *     gps_info = 1
 *
 * ВАЖНО:
 *
 * Здесь НЕ выполняются:
 *
 * - поиск $GNRMC;
 * - проверка checksum;
 * - преобразование координат;
 * - синхронизация RTC;
 * - проверка спуфинга;
 * - проверка области разведки;
 * - переходы стейт-машины;
 * - блокирующие задержки.
 *
 * Callback должен оставаться максимально коротким.
 */
void GPS_RxEventCallback(uint16_t size);


/*
 * ============================================================================
 * GPS_NotifyUartError()
 * ============================================================================
 *
 * Вызывается из:
 *
 *     HAL_UART_ErrorCallback()
 *
 * если аппаратная ошибка относится к USART3.
 *
 * Функция только фиксирует наличие ошибки приёма.
 *
 * Никаких переходов стейт-машины непосредственно из callback
 * не выполняется.
 */
void GPS_NotifyUartError(void);


/*
 * ============================================================================
 * GPS_HasRxError()
 * ============================================================================
 *
 * Позволяет основному циклу узнать, была ли зафиксирована аппаратная
 * ошибка USART3/DMA либо внутренняя ошибка накопления принятых данных.
 *
 * Возвращает:
 *
 *     0 - ошибка не зафиксирована;
 *     1 - ошибка зафиксирована.
 *
 * Решение о дальнейшем переходе состояния принимает стейт-машина.
 */
uint8_t GPS_HasRxError(void);


/*
 * ============================================================================
 * GPS_Process()
 * ============================================================================
 *
 * Выполняет обработку накопленных GPS-данных.
 *
 * Функция вызывается из состояния GPS_PROC после обнаружения:
 *
 *     gps_info == 1
 *
 * Функция ищет в накопленных данных корректное предложение:
 *
 *     $GNRMC
 *
 * Корректным считается $GNRMC, из которого можно получить валидные:
 *
 * - координату;
 * - UTC-время;
 * - дату.
 *
 * Также должна выполняться проверка NMEA checksum и статуса валидности
 * данных RMC.
 *
 * Если полный корректный $GNRMC найден:
 *
 *     - структура fix заполняется проверенными данными;
 *     - функция возвращает 1.
 *
 * Если корректного полного $GNRMC пока нет:
 *
 *     - необходимые накопленные данные сохраняются;
 *     - они будут дополнены при следующем событии приёма;
 *     - функция возвращает 0.
 *
 * ВАЖНО:
 *
 * Отсутствие полного $GNRMC в текущей порции данных НЕ является
 * ошибкой GPS.
 *
 * Контроль того, сколько времени LOGGER ждёт валидные данные,
 * выполняется отдельно аппаратным таймером TIM3.
 */
uint8_t GPS_Process(GPS_Fix *fix);


/*
 * ============================================================================
 * GPS_Clear()
 * ============================================================================
 *
 * Очищает накопленные данные GPS и сбрасывает внутреннее состояние
 * обработки принятых данных.
 *
 * Также сбрасывается gps_info.
 *
 * Используется после завершения текущего сеанса GPS либо перед
 * началом нового сеанса.
 */
void GPS_Clear(void);


/*
 * ============================================================================
 * GPS_CheckSpoofing()
 * ============================================================================
 *
 * ЗАГЛУШКА ДЛЯ БУДУЩЕЙ РЕАЛИЗАЦИИ.
 *
 * По стейт-машине в MODE_EXPECT и MODE_WORK необходимо сравнивать
 * новую координату с предыдущей валидной координатой и определять:
 *
 * - дрон находится практически в одной точке;
 * - дрон переместился на допустимое расстояние;
 * - перемещение нереально велико и может свидетельствовать
 *   о GPS-спуфинге.
 *
 * При подозрении на спуфинг новая координата не должна становиться
 * последней валидной координатой.
 *
 * После трёх подтверждений спуфинга система должна сообщить
 * о невозможности разведки и перейти в MODE_ERROR.
 *
 * Числовые пороги и окончательный алгоритм пока НЕ определены.
 *
 * Поэтому на текущем этапе функция будет реализована в gps.c
 * как явно обозначенная временная заглушка.
 */
uint8_t GPS_CheckSpoofing(const GPS_Fix *fix);


/*
 * ============================================================================
 * GPS_CheckReconArea()
 * ============================================================================
 *
 * ЗАГЛУШКА ДЛЯ БУДУЩЕЙ РЕАЛИЗАЦИИ.
 *
 * По стейт-машине в MODE_EXPECT и MODE_WORK необходимо определить,
 * находится ли текущая координата внутри области разведки.
 *
 * Геометрическое описание области разведки и окончательный алгоритм
 * проверки пока НЕ определены.
 *
 * Поэтому на текущем этапе функция будет реализована в gps.c
 * как явно обозначенная временная заглушка.
 */
uint8_t GPS_CheckReconArea(const GPS_Fix *fix);


#endif /* LOGGER_GPS_H */