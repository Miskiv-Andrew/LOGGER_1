#ifndef LOGGER_STATE_MACHINE_H
#define LOGGER_STATE_MACHINE_H


/* ============================================================================
 * LOGGER
 *
 * Интерфейс основной стейт-машины логгера.
 *
 * В этом файле объявляется состояние LOGGER и функции управления
 * стейт-машиной.
 *
 * Реализация функций будет находиться в logger_state_machine.c.
 * ========================================================================== */


/* ============================================================================
 * Подключение общих типов LOGGER.
 * ========================================================================== */
#include <stdint.h>
#include "logger_types.h"


/* ============================================================================
 * Структура текущего состояния LOGGER.
 *
 * Эта структура содержит основные переменные, определяющие текущее
 * состояние системы.
 *
 * На данном этапе добавляем только фундаментальные состояния.
 * Флаги приборов, счетчики ошибок, параметры области разведки,
 * таймеры и результаты измерений будем добавлять постепенно,
 * когда дойдем до соответствующих частей стейт-машины.
 * ========================================================================== */
typedef struct
{
    /*
     * Глобальный режим работы LOGGER:
     * MODE_TEST, MODE_EXPECT, MODE_WORK, MODE_ERROR или MODE_RETURN.
     */
    ReqMode req_mode;

    /*
     * Текущий режим выполнения измерений:
     * MODE_OPERATOR, MODE_TIME, MODE_DISTANCE,
     * START_SPECTRE или MODE_SPECTRE.
     */
    DroneWorkMode work_mode;

    /*
     * Предыдущий режим измерений.
     *
     * Используется при переходе в режим набора спектра.
     * После завершения спектра LOGGER должен вернуться
     * в режим, который был активен до его запуска.
     */
    DroneWorkMode old_work_mode;

    /*
     * Текущее состояние основной стейт-машины.
     */
    DroneState state;

    /*
     * Прибор, ответ от которого система ожидает в данный момент.
     *
     * DEV_NONE означает, что активного ожидания ответа прибора нет.
     */
    DevType dev_type;

    /*
     * Текущий тип запроса к БДБГ-15.
     */
    BdbgRequest bdbg_request;
		
		/*
		* Указатель на завершённый burst данных RadioLine.
		*
		* Сам буфер физически находится в main.c.
		* После того как TIM6 обнаружит 100 мс тишины,
		* main() передаст сюда адрес накопленного буфера.
		*
		* NULL означает, что готовых данных RadioLine
		* для обработки сейчас нет.
		*/
		const uint8_t *radioline_data;

		/*
		* Количество байтов в завершённом burst RadioLine.
		*
		* Значение действительно только тогда, когда
		* radioline_data != NULL.
		*/
		uint16_t radioline_length;

} LoggerStateMachine;


/* ============================================================================
 * Инициализация стейт-машины LOGGER.
 *
 * Функция устанавливает начальные состояния системы после запуска МК.
 *
 * Реализацию функции добавим в logger_state_machine.c.
 * ========================================================================== */
void LoggerStateMachine_Init(LoggerStateMachine *logger);



/* ============================================================================
 * Передача завершённого burst RadioLine в стейт-машину.
 *
 * Функция вызывается из main(), а НЕ из прерывания.
 *
 * data   - указатель на накопленные данные RadioLine;
 * length - количество принятых байтов.
 *
 * Функция только передаёт информацию стейт-машине.
 * Разбор структуры пакета, CRC и Command ID здесь не выполняется.
 * ========================================================================== */
void LoggerStateMachine_SetRadioLineData(LoggerStateMachine *logger,
                                         const uint8_t *data,
                                         uint16_t length);



/* ============================================================================
 * Выполнение одного шага основной стейт-машины.
 *
 * В дальнейшем эта функция будет периодически вызываться из главного
 * цикла программы.
 *
 * Один вызов функции обрабатывает текущее состояние LOGGER и возвращает
 * управление в main().
 *
 * Функция не должна содержать бесконечных циклов ожидания.
 * ========================================================================== */
void LoggerStateMachine_Process(LoggerStateMachine *logger);


#endif /* LOGGER_STATE_MACHINE_H */