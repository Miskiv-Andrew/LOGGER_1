
#ifndef LOGGER_STATE_MACHINE_H
#define LOGGER_STATE_MACHINE_H

/* ============================================================================
 * LOGGER
 *
 * Интерфейс основной стейт-машины логгера.
 *
 * В этом файле объявляется состояние LOGGER и функции управления
 * стейт-машиной.
 *
 * Реализация функций находится в logger_state_machine.c.
 * ========================================================================== */


/* ============================================================================
 * Подключение общих типов LOGGER.
 *
 * logger_types.h содержит:
 *
 * - перечисления режимов и состояний LOGGER;
 * - структуру Coord;
 * - структуру FlightConfig;
 * - структуру GPS_TimeStamp;
 * - структуру GPS_Data;
 * - константы контроля GPS и параметров разведки.
 * ========================================================================== */

#include <stdint.h>
#include "logger_types.h"
#include "bdbg.h"
#include "lidar.h"


/* ============================================================================
 * Флаг срабатывания общего таймера контроля ответа прибора.
 *
 * Таймер TIM3 используется для контроля времени ожидания ответа
 * от текущего прибора.
 *
 * Флаг устанавливается в HAL_TIM_PeriodElapsedCallback()
 * при срабатывании TIM3.
 *
 * Обработка причины таймаута выполняется только
 * в основной стейт-машине.
 *
 * В обработчике прерывания никакие переходы состояний не выполняются.
 *
 * Прибор, ответ которого ожидался, определяется по:
 *
 *     logger->dev_type
 *
 * 0 - таймер контроля ответа не срабатывал;
 * 1 - время ожидания ответа прибора истекло.
 * ========================================================================== */

extern volatile uint8_t device_timeout;



/*
 * Интервал периодического запроса GPS
 * в режимах MODE_EXPECT и MODE_RETURN.
 * Единица измерения — секунды.
 */
#define LOGGER_ROUTE_GPS_INTERVAL_S 10U

/*
 * Интервал периодического запроса GPS
 * в режиме MODE_WORK / MODE_DISTANCE.
 * Единица измерения — секунды.
 */
#define LOGGER_DISTANCE_GPS_INTERVAL_S 10U




/* ============================================================================
 * Структура текущего состояния LOGGER.
 *
 * Содержит:
 *
 * - глобальный режим работы;
 * - режим выполнения измерений;
 * - текущее состояние стейт-машины;
 * - информацию об обслуживаемом приборе;
 * - счётчики ошибок;
 * - параметры радиационной разведки;
 * - координаты и временные метки GPS;
 * - информацию о принятых данных RadioLine.
 *
 * Все данные размещаются непосредственно в структуре.
 *
 * Динамическое выделение памяти не используется.
 * ========================================================================== */

typedef struct
{
    /*
     * Глобальный режим работы LOGGER:
     *
     * MODE_TEST   - предполётная проверка;
     * MODE_EXPECT - ожидание входа в область разведки;
     * MODE_WORK   - выполнение разведки;
     * MODE_ERROR  - терминальная ошибка;
     * MODE_RETURN - возвращение.
     */
    ReqMode req_mode;

    /*
     * Текущий режим выполнения измерений:
     *
     * MODE_OPERATOR;
     * MODE_TIME;
     * MODE_DISTANCE;
     * START_SPECTRE;
     * MODE_SPECTRE.
     */
    DroneWorkMode work_mode;

    /*
     * Предыдущий режим измерений.
     *
     * Используется при переходе в режим набора спектра.
     *
     * После завершения спектра LOGGER возвращается
     * к предыдущему режиму работы.
     */
    DroneWorkMode old_work_mode;

    /*
     * Текущее состояние основной стейт-машины.
     */
    DroneState state;

    /*
     * Прибор, ответ от которого ожидается в данный момент.
     *
     * DEV_NONE означает отсутствие активного ожидания.
     *
     * Используется в том числе обработчиком тайм-аута TIM3.
     */
    DevType dev_type;
		
		
		/*
		 * Управление программным интервалом LOGGER.
		 *
		 * interval_control_active:
		 * 0 - отсчёт интервала отключён;
		 * 1 - отсчёт интервала активен.
		 *
		 * interval_start_seconds:
		 * Значение глобального счётчика rtc_seconds
		 * в момент запуска текущего интервала.
		 *
		 * Глобальный счётчик RTC не сбрасывается.
		 * Прошедшее время вычисляется как разность
		 * rtc_seconds - interval_start_seconds.
		 *
		 * При выполнении цикла опроса приборов отсчёт
		 * интервала отключается. После завершения цикла
		 * начало нового интервала фиксируется заново.
		 */
		uint8_t interval_control_active;
		uint32_t interval_start_seconds;


    /* ========================================================================
     * Счётчики последовательных ошибок приборов.
     *
     * При получении корректных данных соответствующий
     * счётчик сбрасывается в 0.
     * ====================================================================== */

    uint8_t bdbg_error_counter;
		
		
    /*
     * ============================================================
     * ОЖИДАНИЕ ПОВТОРНОГО START_SPECTRE_REQ
     * ============================================================
     *
     * bdbg_start_retry_pending:
     *
     * 0 - повторный запрос не ожидается;
     * 1 - ожидается истечение интервала перед повтором.
     *
     * Признак используется в состоянии COMMAND_INFO.
     */
    uint8_t bdbg_start_retry_pending;

    /*
     * Время возникновения последней ошибки запуска
     * спектра, полученное через HAL_GetTick().
     *
     * Единицы измерения - миллисекунды.
     *
     * Интервал вычисляется вычитанием текущего значения
     * HAL_GetTick() и сохранённого значения.
     *
     * Такое вычисление корректно и при переполнении
     * 32-битного счётчика HAL_GetTick().
     */
    uint32_t bdbg_start_retry_tick;	


    /*
     * Количество последовательных ошибок получения
     * корректных данных GPS.
     *
     * Не используется для подсчёта обнаружений спуфинга.
     */
    uint8_t gps_error_counter;

    uint8_t lidar_error_counter;

    uint8_t batt_error_counter;
		
		
		/*
		 * Счётчик последовательных измерений аккумулятора,
		 * при которых напряжение оказалось ниже критического.
		 *
		 * Увеличивается только после успешного получения
		 * всех 10 результатов ADC и вычисления среднего
		 * напряжения.
		 *
		 * Если измеренное напряжение не ниже порога
		 * LOGGER_BATTERY_CRITICAL_V, счётчик сбрасывается.
		 *
		 * При достижении LOGGER_DEVICE_ERROR_LIMIT
		 * дальнейшая разведка прекращается.
		 *
		 * Ошибки ADC этот счётчик не увеличивают
		 * и не сбрасывают.
		 */
		uint8_t batt_low_voltage_counter;

		
		/*
		* Счётчик последовательных ошибок чтения RTC.
		*
		* Увеличивается при ошибке RTC_Service_GetTime().
		* Сбрасывается после успешного чтения RTC.
		*
		* Не связан со счётчиком ошибок GPS.
		*/
		uint8_t rtc_error_counter;


    /* ========================================================================
     * Счётчик обнаружений спуфинга GPS.
     *
     * Учитывает последовательные подозрительные GPS-измерения.
     *
     * При обнаружении подозрительной координаты или времени
     * значение увеличивается.
     *
     * При получении валидных данных счётчик обнуляется.
     *
     * После LOGGER_GPS_SPOOFING_LIMIT последовательных
     * обнаружений спуфинг считается подтверждённым.
     *
     * Этот счётчик независим от gps_error_counter.
     * ====================================================================== */

    uint8_t gps_spoofing_counter;


    /* ========================================================================
     * Параметры радиационной разведки.
     *
     * Заполняются после успешного приёма команды ID04.
     *
     * Содержат:
     *
     * - количество вершин области;
     * - статический массив из 20 координат;
     * - режим выполнения измерений;
     * - интервал сохранения;
     * - минимальную дистанцию сохранения;
     * - коэффициент дублирования радиопакетов;
     * - время набора спектра.
     *
     * Параметры сохраняются только в RAM.
     *
     * При повторном получении корректной команды ID04
     * действующая конфигурация заменяется новой.
     * ====================================================================== */

   
		/*
		 * Действующая конфигурация территории разведки.
		 *
		 * Используется до полного завершения перехода
		 * на новую территорию.
		 */
		FlightConfig flight_config;

		/*
		 * Новая конфигурация, полученная командой ID04.
		 *
		 * Хранится отдельно от действующей конфигурации,
		 * пока FLIGHT_CHANGE завершает работу
		 * с предыдущей территорией.
		 */
		FlightConfig pending_flight_config;

		/*
		 * Признак незавершённой смены территории:
		 *
		 * 0 — новая конфигурация не ожидает применения;
		 * 1 — новая конфигурация принята, переход
		 *     на новую территорию ещё не завершён.
		 *
		 * Пока значение равно 1, повторный ID04
		 * должен отклоняться с ответом ID02.
		 */
		uint8_t new_flight_config_pending;		


    /* ========================================================================
     * Данные GPS для работы основной стейт-машины.
     *
     * Содержат:
     *
     * - последнюю валидную координату;
     * - текущую координату;
     * - последнюю координату сохранения измерений;
     * - соответствующие временные метки;
     * - расстояния между точками;
     * - признаки наличия опорных координат.
     *
     * Данные используются для:
     *
     * - проверки спуфинга;
     * - проверки принадлежности области разведки;
     * - принятия решения о выполнении очередного измерения;
     * - формирования результатов радиационной разведки.
     *
     * Приём и разбор NMEA остаются в gps.c.
     *
     * Все проверки и решения выполняются
     * в logger_state_machine.c.
     * ====================================================================== */

    GPS_Data gps_data;
		
		
	
			/*
			* ================================================================
			* GPS-координаты и высота LIDAR в момент запуска набора спектра.
			*
			* Значения фиксируются в LIDAR_PROC перед START_SPECTRE_REQ.
			* В течение всего набора спектра не изменяются.
			*
			* Используются при сохранении накопленного спектра на SD-карту.
			* ================================================================
			*/

			/* GPS-координаты начала набора спектра. */
			Coord spectrum_start_coord;

			/* Высота LIDAR в момент начала набора спектра, сантиметры. */
			uint16_t spectrum_start_height_cm;

			/*
			* Признак наличия зафиксированных данных:
			*
			* 0 — данные начала спектра отсутствуют;
			* 1 — координаты и высота зафиксированы.
			*/
			uint8_t spectrum_start_data_valid;			
			
			/*
			 * Порядковый номер спектра в текущем сеансе работы LOGGER.
			 *
			 * При запуске LOGGER равен 0.
			 * После успешного подтверждения START_SPECTRE_REQ
			 * увеличивается на 1.
			 *
			 * Первый спектр имеет номер 1.
			 * EEPROM для хранения счётчика не используется.
			 */
			uint16_t spectrum_sequence_number;

			/*
			 * Дата и время начала текущего набора спектра.
			 *
			 * Фиксируются по RTC после успешного подтверждения
			 * START_SPECTRE_REQ.
			 *
			 * Используются для формирования идентификатора
			 * спектра и последующей записи на SD-карту.
			 *
			 * Формат GPS_TimeStamp:
			 * год, месяц, день, часы, минуты, секунды.
			 */
			GPS_TimeStamp spectrum_start_time;		
	
			
			/* Высота LIDAR последнего сохранённого измерения, см. */
			uint16_t last_saved_lidar_height_cm;

			/* 1 — сохранённая высота имеется, 0 — отсутствует. */
			uint8_t has_last_saved_lidar_height;
			

			/* ========================================================================
			 * Текущий тип запроса к БДБГ-15.
			 * ====================================================================== */

			BdbgRequest bdbg_request;
			/* Последняя корректная порция данных прибора. */
			BDBG_Data bdbg_data;
			/* Сумма спектров по каналам, без динамического выделения памяти. */
			uint16_t spectre_arr[BDBG_SPECTRUM_CHANNELS];
			
			/*
			 * Признак активного набора спектра БДБГ-15.
			 * 1 — спектральный режим запущен.
			 * 0 — набор не выполняется.
			 */
			uint8_t bdbg_spectrum_active;

		/*
		 * Признак процедуры завершения спектрального режима.
		 *
		 * 0 — обычный обмен с БДБГ.
		 * 1 — PAED_REQ отправляется для остановки набора спектра.
		 *
		 * При установленном признаке ответ PAED_REQ не должен
		 * запускать следующий запрос TEMP_REQ.
		 */
		uint8_t bdbg_spectrum_stopping;		
		
		
		/*
		 * Признак аварийного завершения спектрального режима.
		 *
		 * 0 — штатная остановка набора спектра.
		 * 1 — остановка вызвана отказом GET_SPECTRE_REQ.
		 *
		 * После остановки БДБГ необходимо сохранить
		 * накопленный спектр и перейти в MODE_ERROR.
		 */
		uint8_t bdbg_spectrum_error_shutdown;		
		

		/* Время начала набора спектра по секундному счётчику RTC. */
		uint32_t bdbg_spectrum_started_s;

		/* Время завершения обработки предыдущей порции спектра. */
		uint32_t bdbg_last_poll_s;
				
		/*
		 * Последнее корректное измерение LIDAR.
		 *
		 * Сохраняется в LIDAR_PROC после успешного разбора ответа.
		 * Используется при формировании пакета ID22 в WORK_SD.
		 *
		 * distance_cm — расстояние, см (uint16_t).
		 * strength    — сила сигнала (uint16_t).
		 */
		LIDAR_Data lidar_data;


    /* ========================================================================
     * Данные RadioLine.
     * ====================================================================== */

    /*
     * Указатель на завершённый burst данных RadioLine.
     *
     * Сам буфер физически находится в main.c.
     *
     * После обнаружения паузы 100 мс TIM6 сообщает
     * о завершении приёма.
     *
     * main() передаёт сюда адрес накопленного буфера.
     *
     * Указатель не владеет памятью и не выделяет её.
     *
     * NULL означает отсутствие готовых данных.
     */
    const uint8_t *radioline_data;

    /*
     * Количество байтов в завершённом burst RadioLine.
     *
     * Значение действительно только тогда,
     * когда radioline_data != NULL.
     */
    uint16_t radioline_length;
		
		
        /*
         * Координата последнего сохранённого полного измерения
         * и признак её наличия хранятся в gps_data:
         * last_saved_coord и has_last_saved_coord.
         * Обновление после успешной записи на SD пока заглушка.
         */
		 /*
		 * Напряжение аккумулятора, В.
		 *
		 * Временно используется отладочное значение 1.0f.
		 * После реализации измерения аккумулятора
		 * поле будет содержать фактическое напряжение.
		 */
		float battery_voltage;	
		
		/*
		 * ============================================================
		 * НАКОПЛЕНИЕ РЕЗУЛЬТАТОВ ИЗМЕРЕНИЙ АККУМУЛЯТОРА
		 * ============================================================
		 *
		 * Один полный цикл измерения аккумулятора состоит
		 * из LOGGER_BATTERY_ADC_SAMPLES преобразований ADC1.
		 *
		 * Результаты накапливаются в основной стейт-машине,
		 * а не в обработчике прерывания.
		 */

		/*
		 * Сумма цифровых результатов ADC1.
		 *
		 * Используем uint32_t, поскольку сумма десяти
		 * 12-битных результатов может превышать 65535
		 * при увеличении количества измерений в будущем.
		 *
		 * Перед каждым новым циклом измерений
		 * значение сбрасывается в ноль.
		 */
		uint32_t battery_adc_sum;

		/*
		 * Количество успешно обработанных преобразований
		 * в текущем цикле измерений аккумулятора.
		 *
		 * После достижения LOGGER_BATTERY_ADC_SAMPLES
		 * вычисляется среднее напряжение.
		 */
		uint8_t battery_adc_count;	

		
		/*
		 * Повтор опроса при подготовке спектра:
		 * 0 — повтор не требуется;
		 * 1 — повтор GPS;
		 * 2 — повтор LIDAR.
		 *
		 * Признак используется только в START_SPECTRE.
		 */
		uint8_t spectrum_prepare_retry;


} LoggerStateMachine;




/* ============================================================================
 * Инициализация стейт-машины LOGGER.
 *
 * Устанавливает начальные значения после запуска STM32.
 * ========================================================================== */

void LoggerStateMachine_Init(LoggerStateMachine *logger);


/* ============================================================================
 * Передача завершённого burst RadioLine в стейт-машину.
 *
 * Вызывается из main(), а не из обработчика прерывания.
 *
 * data   - адрес накопленных данных RadioLine;
 * length - количество принятых байтов.
 *
 * Разбор пакета и проверка CRC здесь не выполняются.
 * ========================================================================== */

void LoggerStateMachine_SetRadioLineData(LoggerStateMachine *logger,
                                         const uint8_t *data,
                                         uint16_t length);


/* ============================================================================
 * Выполнение одного шага основной стейт-машины.
 *
 * Вызывается из главного цикла программы.
 *
 * Один вызов обрабатывает только текущее состояние
 * и возвращает управление в main().
 *
 * Бесконечные циклы ожидания не допускаются.
 * ========================================================================== */

void LoggerStateMachine_Process(LoggerStateMachine *logger);


#endif /* LOGGER_STATE_MACHINE_H */
