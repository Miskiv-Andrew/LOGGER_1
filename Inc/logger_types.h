#ifndef LOGGER_TYPES_H
#define LOGGER_TYPES_H


/* ============================================================================
 * Основные константы LOGGER
 * ========================================================================== */

/*
 * Максимальное количество вершин области радиационной разведки.
 * Область передается с земли и может содержать не более 20 точек.
 */
#define LOGGER_MAX_AREA_POINTS          20U

/*
 * Минимальное количество вершин области радиационной разведки.
 */
#define LOGGER_MIN_AREA_POINTS          3U

/*
 * Начальное время набора спектра, секунд.
 *
 * После запуска системы используется 60 секунд.
 * В дальнейшем оператор может изменить это значение командой с земли.
 */
#define LOGGER_DEFAULT_SPECTRUM_TIME    60U

/*
 * Начальный коэффициент дублирования радиопакетов.
 *
 * Каждый передаваемый пакет отправляется два раза, если оператор
 * не изменил коэффициент соответствующей командой.
 */
#define LOGGER_DEFAULT_REPEAT_FACTOR    2U

/*
 * Допустимые границы коэффициента дублирования радиопакетов.
 */
#define LOGGER_MIN_REPEAT_FACTOR        2U
#define LOGGER_MAX_REPEAT_FACTOR        5U

/*
 * Максимальное количество последовательных ошибок прибора.
 *
 * Значение 3 пока является исходным. В процессе испытаний системы
 * этот порог может быть изменен.
 */
#define LOGGER_DEVICE_ERROR_LIMIT       3U

/* ============================================================================
 * LOGGER
 *
 * Общие типы данных для стейт-машины логгера.
 *
 * В этом файле находятся только общие перечисления и типы.
 * Здесь не должно быть работы с UART, DMA, GPIO, SD-картой и другой
 * периферией STM32.
 * ========================================================================== */


/* ============================================================================
 * Режим работы всей системы LOGGER
 *
 * ReqMode определяет глобальный режим, в котором сейчас находится система.
 * Это НЕ режим выполнения измерений (DroneWorkMode) и НЕ текущее состояние
 * стейт-машины (DroneState).
 * ========================================================================== */
typedef enum
{
    MODE_TEST = 0,      /* Предполетная проверка оборудования. */

    MODE_EXPECT,        /* Ожидание входа БПЛА в область радиационной разведки. */

    MODE_WORK,          /* Выполнение радиационной разведки. */

    MODE_ERROR,         /* Терминальная ошибка системы. */

    MODE_RETURN         /* Возврат / перемещение вне активной разведки. */

} ReqMode;


/* ============================================================================
 * Режим выполнения радиационных измерений
 *
 * DroneWorkMode определяет, ПО КАКОМУ ПРИНЦИПУ выполняются измерения
 * при нахождении системы в MODE_WORK.
 * ========================================================================== */
typedef enum
{
    MODE_OPERATOR = 0,  /* Измерение выполняется по команде оператора. */

    MODE_TIME,          /* Измерения выполняются через заданный интервал времени. */

    MODE_DISTANCE,      /* Измерения выполняются по расстоянию или изменению высоты. */

    START_SPECTRE,      /* Подготовка и запуск режима набора спектра. */

    MODE_SPECTRE        /* Выполняется набор спектра. */

} DroneWorkMode;


/* ============================================================================
 * Текущее состояние основной стейт-машины LOGGER
 *
 * DroneState показывает, какое действие система должна выполнить сейчас.
 * ========================================================================== */
typedef enum
{
    COMMAND_INFO = 0,   /* Обработка команд и основное состояние ожидания. */

    REQ_GPS,            /* Запуск запроса / приема данных GPS. */
    GPS_PROC,           /* Обработка полученных данных GPS. */
    GPS_ERROR_PROC,     /* Обработка ошибки GPS. */

    REQ_LIDAR,          /* Запуск запроса к LIDAR. */
    LIDAR_PROC,         /* Обработка ответа LIDAR. */
    LIDAR_ERROR_PROC,   /* Обработка ошибки LIDAR. */

    REQ_BDBG,           /* Запуск запроса к БДБГ-15. */
    BDBG_PROC,          /* Обработка ответа БДБГ-15. */
    BDBG_ERROR_PROC,    /* Обработка ошибки БДБГ-15. */

    REQ_BATTERY,        /* Запуск измерения напряжения аккумулятора. */
    BATTERY_PROC,       /* Обработка результата измерения аккумулятора. */
    BATTERY_ERROR_PROC, /* Обработка ошибки измерения аккумулятора. */

    WORK_SD             /* Формирование результата и работа с SD-картой. */

} DroneState;


/* ============================================================================
 * Прибор, который в данный момент обслуживается стейт-машиной.
 *
 * Значение используется, в частности, для определения источника ожидаемого
 * ответа и обработки тайм-аута прибора.
 * ========================================================================== */
typedef enum
{
    DEV_NONE = 0,       /* В данный момент ответ ни от какого прибора не ожидается. */

    DEV_GPS,            /* GPS-приемник. */

    DEV_LIDAR,          /* LIDAR. */

    DEV_BDBG,           /* Дозиметр БДБГ-15. */

    DEV_BATTERY         /* Контроль аккумулятора. */

} DevType;


/* ============================================================================
 * Тип текущего запроса к БДБГ-15.
 *
 * БДБГ используется как для обычного измерения ПАЕД/температуры,
 * так и для работы со спектром.
 * ========================================================================== */
typedef enum
{
    PAED_REQ = 0,       /* Запрос ПАЕД. */

    TEMP_REQ,           /* Запрос температуры БДБГ. */

    START_SPECTRE_REQ,  /* Команда запуска набора спектра. */

    GET_SPECTRE_REQ     /* Запрос очередного фрагмента спектра. */

} BdbgRequest;


#endif /* LOGGER_TYPES_H */