
#ifndef LOGGER_TYPES_H
#define LOGGER_TYPES_H

#include <stdint.h>

/* ============================================================================
 * LOGGER
 *
 * Общие константы и типы данных.
 *
 * Здесь объявляются только типы и константы.
 *
 * Работа с UART, DMA, GPIO, RTC, SD-картой и другой периферией
 * выполняется в соответствующих модулях программы.
 * ========================================================================== */


/* ============================================================================
 * 1. ОСНОВНЫЕ КОНСТАНТЫ LOGGER
 * ========================================================================== */

/*
 * Максимальное количество вершин области радиационной разведки.
 *
 * Область задаётся выпуклым многоугольником.
 * Вершины передаются наземной станцией последовательно
 * вдоль границы многоугольника.
 */
#define LOGGER_MAX_AREA_POINTS          20U

/*
 * Минимальное количество вершин многоугольника.
 */
#define LOGGER_MIN_AREA_POINTS          3U

/*
 * Начальное время набора спектра, секунд.
 *
 * После запуска используется 60 секунд.
 * В дальнейшем значение может изменяться командой оператора.
 */
#define LOGGER_DEFAULT_SPECTRUM_TIME    60U

/*
 * Начальный коэффициент дублирования пакетов RadioLine.
 */
#define LOGGER_DEFAULT_REPEAT_FACTOR    2U

/*
 * Допустимые границы коэффициента дублирования.
 */
#define LOGGER_MIN_REPEAT_FACTOR        2U
#define LOGGER_MAX_REPEAT_FACTOR        5U

/*
 * Максимальное количество последовательных ошибок прибора.
 *
 * Значение может быть изменено по результатам испытаний.
 */
#define LOGGER_DEVICE_ERROR_LIMIT       3U


/* Минимальное изменение высоты для выполнения нового измерения, см. */
#define LOGGER_MIN_HEIGHT_CHANGE_CM 500U



/* ============================================================================
 * 2. КОНСТАНТЫ КОНТРОЛЯ СПУФИНГА GPS
 * ========================================================================== */

/*
 * Максимальный допустимый абсолютный скачок координат.
 *
 * Единица измерения: метры.
 *
 * Если расстояние между последней валидной координатой
 * и новой координатой превышает 50 000 метров,
 * новая координата считается подозрительной.
 */
#define LOGGER_GPS_MAX_JUMP_M           50000.0f

/*
 * Максимальная допустимая скорость перемещения.
 *
 * Единица измерения: метры в минуту.
 *
 * Интервал времени между измерениями определяется по RTC,
 * а не по времени, полученному от GPS.
 *
 * Если вычисленная скорость превышает 2000 м/мин,
 * новая координата считается подозрительной.
 */
#define LOGGER_GPS_MAX_SPEED_M_PER_MIN  2000.0f

/*
 * Максимальное допустимое расхождение времени GPS и RTC.
 *
 * Единица измерения: секунды.
 *
 * Сравниваются полные дата и время.
 *
 * Если абсолютное расхождение превышает 1800 секунд,
 * полученные GPS-данные считаются подозрительными.
 */
#define LOGGER_GPS_MAX_TIME_DIFF_S      1800U

/*
 * Количество последовательных обнаружений спуфинга,
 * после которого спуфинг считается подтверждённым.
 *
 * Счётчик спуфинга не связан со счётчиком ошибок
 * получения корректных GPS-данных.
 */
#define LOGGER_GPS_SPOOFING_LIMIT       3U



/* ============================================================================
 * 3. РЕЖИМ РАБОТЫ ВСЕЙ СИСТЕМЫ LOGGER
 *
 * ReqMode определяет глобальный режим работы системы.
 *
 * Это не режим выполнения измерений DroneWorkMode
 * и не текущее состояние DroneState.
 * ========================================================================== */

typedef enum
{
    MODE_TEST = 0,      /* Предполётная проверка оборудования. */

    MODE_EXPECT,        /* Ожидание входа в область разведки. */

    MODE_WORK,          /* Выполнение радиационной разведки. */

    MODE_ERROR,         /* Терминальная ошибка системы. */

    MODE_RETURN         /* Возврат / перемещение вне активной разведки. */

} ReqMode;


/* ============================================================================
 * 4. РЕЖИМ ВЫПОЛНЕНИЯ РАДИАЦИОННЫХ ИЗМЕРЕНИЙ
 *
 * DroneWorkMode определяет принцип выполнения измерений
 * при нахождении системы в MODE_WORK.
 * ========================================================================== */

typedef enum
{
    MODE_OPERATOR = 0,  /* Измерение по команде оператора. */

    MODE_TIME,          /* Измерения через заданный интервал времени. */

    MODE_DISTANCE,      /* Измерения по расстоянию или изменению высоты. */

    START_SPECTRE,      /* Подготовка и запуск набора спектра. */

    MODE_SPECTRE        /* Выполняется набор спектра. */

} DroneWorkMode;


/* ============================================================================
 * 5. ТЕКУЩЕЕ СОСТОЯНИЕ СТЕЙТ-МАШИНЫ
 *
 * DroneState определяет действие, которое LOGGER
 * должен выполнить на текущем шаге.
 * ========================================================================== */

typedef enum
{
    COMMAND_INFO = 0,   /* Обработка команд RadioLine. */

    REQ_GPS,            /* Запуск приёма GPS. */
    GPS_PROC,           /* Обработка GPS-данных. */
    GPS_ERROR_PROC,     /* Обработка ошибки GPS. */

    REQ_LIDAR,          /* Запуск запроса LIDAR. */
    LIDAR_PROC,         /* Обработка ответа LIDAR. */
    LIDAR_ERROR_PROC,   /* Обработка ошибки LIDAR. */

    REQ_BDBG,           /* Запуск запроса БДБГ-15. */
    BDBG_PROC,          /* Обработка ответа БДБГ-15. */
    BDBG_ERROR_PROC,    /* Обработка ошибки БДБГ-15. */

    REQ_BATTERY,        /* Запуск измерения аккумулятора. */
    BATTERY_PROC,       /* Обработка результата измерения. */
    BATTERY_ERROR_PROC, /* Обработка ошибки измерения. */

    WORK_SD             /* Формирование результата и работа с SD-картой. */

} DroneState;


/* ============================================================================
 * 6. ТИП ОБСЛУЖИВАЕМОГО ПРИБОРА
 *
 * DevType используется для определения прибора,
 * ответ которого ожидается в данный момент.
 *
 * В частности, значение используется при обработке TIM3.
 * ========================================================================== */

typedef enum
{
    DEV_NONE = 0,       /* Нет активного ожидания ответа. */

    DEV_GPS,            /* GPS-приёмник. */

    DEV_LIDAR,          /* LIDAR. */

    DEV_BDBG,           /* Дозиметр БДБГ-15. */

    DEV_BATTERY         /* Контроль аккумулятора. */

} DevType;


/* ============================================================================
 * 7. ТИП ЗАПРОСА К БДБГ-15
 * ========================================================================== */

typedef enum
{
    PAED_REQ = 0,       /* Запрос ПАЕД. */

    TEMP_REQ,           /* Запрос температуры. */

    START_SPECTRE_REQ,  /* Запуск набора спектра. */

    GET_SPECTRE_REQ     /* Получение фрагмента спектра. */

} BdbgRequest;


/* ============================================================================
 * 8. СТРУКТУРА КООРДИНАТ
 *
 * Используется:
 *
 * - для хранения вершин области разведки;
 * - для хранения текущей GPS-координаты;
 * - для хранения последней валидной координаты;
 * - для хранения последней точки сохранения измерений.
 *
 * Широта и долгота задаются в десятичных градусах.
 * ========================================================================== */

typedef struct
{
    float lat;          /* Широта, градусы. */

    float lon;          /* Долгота, градусы. */

} Coord;


/* ============================================================================
 * 9. ПАРАМЕТРЫ РАДИАЦИОННОЙ РАЗВЕДКИ
 *
 * FlightConfig содержит параметры, передаваемые наземной станцией
 * командой RadioLine ID04.
 *
 * Данные хранятся только в RAM.
 * После выключения питания параметры не сохраняются.
 *
 * Порядок полей структуры не является форматом радиопакета.
 * Разбор Payload выполняется отдельно в COMMAND_INFO.
 * ========================================================================== */

typedef struct
{
    /*
     * Фактическое количество вершин области разведки.
     *
     * Допустимые значения: от 3 до 20.
     *
     * Значение 0 означает, что параметры области
     * ещё не получены.
     */
    uint8_t pointCount;

    /*
     * Статический массив вершин выпуклого многоугольника.
     *
     * Используются только первые pointCount элементов.
     *
     * Точки располагаются последовательно вдоль границы.
     */
    Coord points[LOGGER_MAX_AREA_POINTS];

    /*
     * Режим выполнения измерений.
     *
     * Значения команды ID04:
     *
     * 0 - MODE_OPERATOR;
     * 1 - MODE_TIME;
     * 2 - MODE_DISTANCE;
     * 3 - запуск режима спектра.
     *
     * Преобразование значения в DroneWorkMode
     * выполняется при обработке команды.
     */
    uint8_t mode;

    /*
     * Интервал между измерениями, секунды.
     */
    uint16_t saveTime;

    /*
     * Минимальное расстояние между точками сохранения
     * измерений, метры.
     *
     * Новый цикл выполняется при:
     *
     * distance >= saveDistance.
     */
    uint16_t saveDistance;

    /*
     * Коэффициент дублирования исходящих пакетов RadioLine.
     *
     * Допустимые значения: 2...5.
     */
    uint8_t duplCoeff;

    /*
     * Время набора спектра, секунды.
     *
     * Значение 0 означает, что параметр не задан
     * в конфигурации разведки.
     */
    uint16_t saveSpectre;

} FlightConfig;


/* ============================================================================
 * 10. ПОЛНАЯ ВРЕМЕННАЯ МЕТКА GPS / RTC
 *
 * Используется для:
 *
 * - сравнения времени GPS с RTC;
 * - хранения времени последней валидной координаты;
 * - вычисления интервала между GPS-измерениями;
 * - правильной обработки перехода через полночь.
 *
 * Все поля даты и времени хранятся отдельно.
 *
 * Преобразование временной метки в секунды
 * будет реализовано в logger_state_machine.c.
 * ========================================================================== */

typedef struct
{
    uint16_t year;      /* Полный год, например 2026. */

    uint8_t month;      /* Месяц: 1...12. */

    uint8_t day;        /* День месяца: 1...31. */

    uint8_t hour;       /* Часы: 0...23. */

    uint8_t minute;     /* Минуты: 0...59. */

    uint8_t second;     /* Секунды: 0...59. */

} GPS_TimeStamp;


/* ============================================================================
 * 11. ДАННЫЕ GPS ДЛЯ ОСНОВНОЙ СТЕЙТ-МАШИНЫ
 *
 * GPS_Data содержит информацию, которая должна сохраняться
 * между отдельными циклами приёма GPS.
 *
 * Модуль gps.c отвечает только за получение и разбор NMEA.
 *
 * Проверка спуфинга, области разведки и условий выполнения
 * измерений будет реализована в logger_state_machine.c.
 * ========================================================================== */

typedef struct
{
    /*
     * Последняя координата, прошедшая проверку спуфинга.
     *
     * Именно с ней сравнивается каждая новая координата.
     *
     * При обнаружении подозрительной координаты
     * last_valid_coord не изменяется.
     */
    Coord last_valid_coord;

    /*
     * Признак наличия последней валидной координаты.
     *
     * 0 - координата ещё не получена;
     * 1 - координата сохранена.
     *
     * Начальная координата устанавливается в MODE_TEST.
     */
    uint8_t has_last_valid_coord;

    /*
     * Время RTC, соответствующее моменту получения
     * последней валидной координаты.
     *
     * Используется для вычисления скорости перемещения.
     */
    GPS_TimeStamp last_valid_rtc_time;

    /*
     * Последняя принятая GPS-координата.
     *
     * Сначала сохраняется сюда для проверки.
     *
     * Только после успешной проверки она может
     * заменить last_valid_coord.
     */
    Coord current_coord;

    /*
     * Дата и время, полученные вместе с current_coord
     * из GPS-пакета.
     */
    GPS_TimeStamp current_gps_time;

    /*
     * Дата и время RTC на момент получения
     * текущих GPS-данных.
     */
    GPS_TimeStamp current_rtc_time;

    /*
     * Последняя координата, для которой был выполнен
     * цикл измерений с сохранением результата.
     *
     * Используется в режиме MODE_DISTANCE.
     *
     * Не следует путать её с last_valid_coord:
     * последняя валидная GPS-координата может обновляться
     * значительно чаще, чем сохраняются измерения.
     */
    Coord last_saved_coord;

    /*
     * Признак наличия последней точки сохранения.
     *
     * 0 - ни одного измерения ещё не сохранено;
     * 1 - last_saved_coord содержит координату
     *     последнего сохранённого измерения.
     */
    uint8_t has_last_saved_coord;

    /*
     * Время RTC последней точки сохранения измерений.
     */
    GPS_TimeStamp last_saved_rtc_time;

    /*
     * Расстояние между последней валидной
     * и текущей координатой, метры.
     *
     * Обновляется после успешной проверки спуфинга.
     */
    float last_move_distance_m;

    /*
     * Расстояние от текущей координаты
     * до последней точки сохранения измерений, метры.
     *
     * Используется для сравнения с saveDistance.
     */
    float distance_from_saved_m;

} GPS_Data;


#endif /* LOGGER_TYPES_H */
